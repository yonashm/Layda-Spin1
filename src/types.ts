export interface WheelSettings {
  radius: number;
  spinDuration: number; // 5 to 12 seconds
  soundEnabled: boolean;
  soundTheme: 'tick' | 'arcade' | 'retro' | 'synth';
  volume: number; // 0 to 1
  winnerAnnounce: boolean; // Voice synthesis
  confettiEnabled: boolean;
  fireworksEnabled: boolean;
  removeWinnerOnDraw: boolean;
  weightedMode: boolean;
  pointerColor: string;
  centerButtonText: string; // "SPIN" or "Click to Spin"
  fontFamily: string; // Inter, Poppins, Space Grotesk, JetBrains Mono
  uppercase: boolean;
  sliceBorderColor: string;
  sliceBorderWidth: number;
  sliceSpacing: number; // Gap between segments
  glowEnabled: boolean;
  glowColor: string;
  backgroundPattern: 'none' | 'dots' | 'grid' | 'particles';
}

export interface WheelEntry {
  id: string;
  text: string;
  weight: number; // For weighted random option
  color?: string; // Optional custom override
}

export interface SavedWheel {
  id: string;
  title: string;
  entries: WheelEntry[];
  colors: string[]; // Dynamic color palette hexes
  settings: WheelSettings;
  isFavorite: boolean;
  created_at: string;
  updated_at: string;
}

export interface SpinResult {
  id: string;
  wheelId: string;
  winnerName: string;
  timestamp: string;
}

